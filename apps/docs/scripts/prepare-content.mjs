import { copyFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Contract files owned by other packages, copied under their published names. */
const CONTRACT_FILES = [
  ['docs/api/openapi.json', 'openapi.json'],
  ['docs/mcp/tools.json', 'tools.json'],
  ['docs/reference/product-reference.json', 'product-reference.json'],
];

/**
 * Copies the three contract files into `<docsDir>/_generated/` and returns the paths written.
 * It writes nowhere else, so versioned snapshots can never be regenerated by accident.
 */
export function prepareContent(repoRoot, docsDir) {
  const outDir = join(docsDir, '_generated');
  mkdirSync(outDir, { recursive: true });
  return CONTRACT_FILES.map(([from, to]) => {
    const target = join(outDir, to);
    copyFileSync(join(repoRoot, from), target);
    return target;
  });
}

/**
 * sidebars.ts imports the sidebar that `docusaurus gen-api-docs` writes. Until that has run (a
 * fresh checkout, `typecheck`, `lint`) this empty one stands in; the generator overwrites it.
 * Returns the path when it wrote one.
 */
export function ensureApiSidebar(docsDir) {
  const file = join(docsDir, 'api/reference/sidebar.ts');
  if (existsSync(file)) return undefined;
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(
    file,
    'import type { SidebarsConfig } from "@docusaurus/plugin-content-docs";\n\nconst sidebar: SidebarsConfig = { apisidebar: [] };\n\nexport default sidebar.apisidebar;\n',
  );
  return file;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const here = dirname(fileURLToPath(import.meta.url));
  const docsDir = resolve(here, '../docs');
  const written = [
    ...prepareContent(resolve(here, '../../..'), docsDir),
    ensureApiSidebar(docsDir),
  ];
  for (const file of written) if (file) console.log(`wrote ${file}`);
}
